CREATE DATABASE IF NOT EXISTS retrogame_recuperacao;
USE retrogame_recuperacao;

CREATE TABLE CLIENTES (
    ID_CLIENTES INT AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    TELEFONE VARCHAR(20),
    ATIVO BOOLEAN DEFAULT TRUE,
    CONSTRAINT PK_CLIENTES PRIMARY KEY (ID_CLIENTES),
    CONSTRAINT UQ_EMAIL UNIQUE (EMAIL)
);

CREATE TABLE PLATAFORMA (
    ID_PLATAFORMA INT AUTO_INCREMENT,
    NOME VARCHAR(60) NOT NULL,
    ANO_PLATAFORMA INT,
    CONSTRAINT PK_PLATAFORMA PRIMARY KEY (ID_PLATAFORMA)
);


CREATE TABLE CATEGORIA (
    ID_CATEGORIA INT AUTO_INCREMENT,
    NOME_CATEGORIA VARCHAR(60) NOT NULL,
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID_CATEGORIA)
);

CREATE TABLE JOGO (
    ID_JOGO INT PRIMARY KEY AUTO_INCREMENT,
    TITULO VARCHAR(150) NOT NULL,
    CODIGO VARCHAR(15) NOT NULL UNIQUE,
    ANO_LANCAMENTO INT NOT NULL,
    QUANTIDADE_DISPONIVEL INT DEFAULT 0 CHECK >= 0,
    ID_PLATAFORMA INT FK_ID_PLATAFORMA FOREIGN KEY,
    ID_CATEGORIA INT FK_CATEGORIA FOREIGN KEY,
    ESTOQUE INT NOT NULL DEFAULT 0,
    CONSTRAINT PK_JOGO PRIMARY KEY (ID_JOGO),
    CONSTRAINT FK_JOGO
);

CREATE TABLE LOCACAO (
    ID_LOCACAO INT PRIMARY KEY AUTO_INCREMENT,
    DATA_RETIRADA DATETIME DEFAULT CURRENT_TIMESTAMP,
    DATA_PREVISTA DATE NOT NULL,
    DATA_DEVOLUCAO DATE NOT NULL,
    STATUS_LOCACAO VARCHAR(20) DEFAULT 'ABERTA' CHECK (STATUS_LOCACAO IN ('ABERTO', 'DEVOLVIDO', 'ATRASADO')),
    ID_CLIENTE INT FK_ID_CLIENTE FOREIGN KEY,
    ID_JOGO INT FK_JOGO FOREIGN KEY
);

