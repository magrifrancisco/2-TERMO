DELIMITER $$
CREATE PROCEDURE BUSCAR_PRODUTOS_POR_NOME(IN p_busca VARCHAR(100))
BEGIN
    SELECT ID_PRODUTO AS CODIGO, NOME, PRECO, ATIVO
